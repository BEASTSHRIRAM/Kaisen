import { useMemo, useState } from 'react';
import { Box, Button, Grid, Typography } from '@mui/material';
import { useNavigate } from 'react-router-dom';
import { Download, Play } from 'lucide-react';
import { INCIDENTS, Incident } from '../../unified/platformData';
import { LAB_SCENARIOS, LabScenarioId } from '../../unified/scenario';
import { useCockpit } from '../../unified/cockpitStore';
import { AttackGraphSvg, DemoBanner, Panel, Tag } from '../../unified/ui';
import { downloadText } from '../../unified/download';
import { ACCENT } from '../../theme';

const SEV_TONE: Record<string, 'danger' | 'warn' | 'grey'> = { CRITICAL: 'danger', HIGH: 'warn', MEDIUM: 'grey' };
const STATUS_TONE: Record<string, 'danger' | 'accent' | 'warn'> = { OPEN: 'danger', CONTAINED: 'accent', REVIEW: 'warn' };

function reportMarkdown(inc: Incident, steps: { title: string; time: string; layer: string; detail: string }[]): string {
  return [
    `# ${inc.id} — ${inc.title}`,
    ``,
    `Severity: ${inc.severity} · Status: ${inc.status} · Opened: ${inc.opened}`,
    `Server: ${inc.server} · Agent: ${inc.agent}`,
    ``,
    `## Summary`,
    inc.summary,
    ``,
    `## Correlated story`,
    ...steps.map((s, i) => `${i + 1}. [${s.time} · ${s.layer}] ${s.title} — ${s.detail}`),
    ``,
    `## Evidence — agent layer`,
    ...inc.agentEvidence.map((e) => `- ${e}`),
    ``,
    `## Evidence — host layer`,
    ...inc.hostEvidence.map((e) => `- ${e}`),
    ``,
    `## Why Kaisen flagged it`,
    inc.shapReason,
    ``,
    `## Suggested action`,
    inc.suggestedAction,
    ``,
    `## Approval state`,
    inc.approval,
    ``,
    `---`,
    `Generated by Kaisen Unified (exhibition demo — incident data is demo data).`,
  ].join('\n');
}

// INCIDENTS — list + detail. Demo records; INC-1042's story is the playable
// Attack Lab scenario, the rest are written from the same scenario shapes.
export default function IncidentsPage() {
  const navigate = useNavigate();
  const launchScenario = useCockpit((s) => s.launchScenario);
  const [selectedId, setSelectedId] = useState('INC-1042');
  const inc = useMemo(() => INCIDENTS.find((i) => i.id === selectedId)!, [selectedId]);

  const scenario = inc.labScenarioId ? LAB_SCENARIOS[inc.labScenarioId as LabScenarioId] : undefined;
  const steps = scenario ? scenario.frames[scenario.frames.length - 1].incidentSteps : inc.steps;
  const graphData = scenario?.graph;

  return (
    <Box>
      <Box sx={{ mb: 2.5 }}>
        <Typography variant="h4">Incidents</Typography>
        <Typography color="text.secondary" sx={{ mt: 0.5 }}>
          Every incident is one correlated story across the agent and host layers — with the evidence,
          the reasoning, and the human decision attached.
        </Typography>
      </Box>

      <DemoBanner />

      <Grid container spacing={2}>
        <Grid item xs={12} lg={4}>
          <Box sx={{ display: 'flex', flexDirection: 'column', gap: 1.25 }}>
            {INCIDENTS.map((i) => (
              <Box
                key={i.id}
                onClick={() => setSelectedId(i.id)}
                sx={{
                  p: 2, borderRadius: '12px', cursor: 'pointer',
                  bgcolor: 'background.paper',
                  border: `1px solid ${i.id === selectedId ? ACCENT : 'rgba(255,255,255,0.08)'}`,
                  transition: 'border-color 150ms',
                }}
              >
                <Box sx={{ display: 'flex', gap: 0.75, alignItems: 'center', flexWrap: 'wrap' }}>
                  <Typography className="mono" variant="caption" color="text.secondary">{i.id}</Typography>
                  <Tag tone={SEV_TONE[i.severity]}>{i.severity}</Tag>
                  <Tag tone={STATUS_TONE[i.status]}>{i.status}</Tag>
                  <Typography variant="caption" color="text.secondary" sx={{ ml: 'auto' }}>{i.opened}</Typography>
                </Box>
                <Typography sx={{ fontWeight: 620, mt: 1, lineHeight: 1.35 }}>{i.title}</Typography>
                <Typography variant="caption" color="text.secondary">{i.server} · {i.agent}</Typography>
              </Box>
            ))}
          </Box>
        </Grid>

        <Grid item xs={12} lg={8}>
          <Box sx={{ display: 'flex', flexDirection: 'column', gap: 2 }}>
            <Panel
              title={`${inc.id} · ${inc.status}`}
              right={
                <Box sx={{ display: 'flex', gap: 1 }}>
                  {scenario && (
                    <Button size="small" variant="outlined" startIcon={<Play size={13} />} onClick={() => { launchScenario(scenario.id); navigate('/app/cockpit'); }} sx={{ borderColor: 'rgba(255,255,255,0.2)', color: 'text.primary' }}>
                      Replay in Cockpit
                    </Button>
                  )}
                  <Button size="small" variant="contained" startIcon={<Download size={13} />} onClick={() => downloadText(`${inc.id}-report.md`, reportMarkdown(inc, steps), 'text/markdown')} sx={{ bgcolor: ACCENT, color: '#FCFFFF', fontWeight: 700, '&:hover': { bgcolor: '#4DB6E8' } }}>
                    Export report
                  </Button>
                </Box>
              }
            >
              <Typography sx={{ fontWeight: 680, fontSize: '1.25rem', lineHeight: 1.3 }}>{inc.title}</Typography>
              <Typography variant="body2" color="text.secondary" sx={{ mt: 0.75, lineHeight: 1.65 }}>{inc.summary}</Typography>

              <Typography variant="caption" sx={{ display: 'block', mt: 3, mb: 1.25, textTransform: 'uppercase', letterSpacing: '0.12em', color: 'text.secondary', fontWeight: 650 }}>
                The story
              </Typography>
              <Box>
                {steps.map((step, idx) => (
                  <Box key={step.id} className="kaisen-rise" sx={{ display: 'flex', gap: 1.75, pb: idx === steps.length - 1 ? 0 : 2, position: 'relative' }}>
                    {idx < steps.length - 1 && <Box sx={{ position: 'absolute', left: 13, top: 30, bottom: 0, width: '1px', bgcolor: 'rgba(255,255,255,0.12)' }} />}
                    <Box sx={{ width: 27, height: 27, borderRadius: '50%', flexShrink: 0, zIndex: 1, display: 'flex', alignItems: 'center', justifyContent: 'center', border: '1px solid rgba(255,255,255,0.2)', bgcolor: '#0A1218', fontSize: '0.7rem', fontWeight: 700 }}>{idx + 1}</Box>
                    <Box sx={{ pt: 0.3 }}>
                      <Box sx={{ display: 'flex', gap: 1, alignItems: 'center', flexWrap: 'wrap' }}>
                        <Typography className="mono" variant="caption" color="text.secondary">{step.time}</Typography>
                        <Tag tone={step.layer === 'CORRELATION' ? 'danger' : step.layer === 'HOST' ? 'warn' : 'grey'}>{step.layer}</Tag>
                        <Typography sx={{ fontWeight: 620 }}>{step.title}</Typography>
                      </Box>
                      <Typography variant="body2" color="text.secondary" sx={{ mt: 0.5, lineHeight: 1.6 }}>{step.detail}</Typography>
                    </Box>
                  </Box>
                ))}
              </Box>
            </Panel>

            <Grid container spacing={2}>
              <Grid item xs={12} md={6}>
                <Panel title="Attack graph">
                  {graphData ? <AttackGraphSvg graph={graphData} height={250} /> : <Typography color="text.secondary">No graph for this incident.</Typography>}
                </Panel>
              </Grid>
              <Grid item xs={12} md={6}>
                <Box sx={{ display: 'flex', flexDirection: 'column', gap: 2 }}>
                  <Panel title="Evidence">
                    <Typography variant="caption" sx={{ fontWeight: 700, color: ACCENT, letterSpacing: '0.08em' }}>AGENT LAYER</Typography>
                    {inc.agentEvidence.map((e) => (
                      <Typography key={e} variant="body2" sx={{ mt: 0.6 }}>· {e}</Typography>
                    ))}
                    <Typography variant="caption" sx={{ fontWeight: 700, color: ACCENT, letterSpacing: '0.08em', display: 'block', mt: 1.75 }}>HOST LAYER</Typography>
                    {inc.hostEvidence.map((e) => (
                      <Typography key={e} variant="body2" sx={{ mt: 0.6 }}>· {e}</Typography>
                    ))}
                  </Panel>
                  <Panel title="Why — plain-language reasons">
                    <Typography variant="body2" sx={{ lineHeight: 1.65 }}>{inc.shapReason}</Typography>
                  </Panel>
                </Box>
              </Grid>
            </Grid>

            <Panel title="Suggested action & approval">
              <Box sx={{ display: 'flex', justifyContent: 'space-between', gap: 2, flexWrap: 'wrap', alignItems: 'center' }}>
                <Box>
                  <Typography sx={{ fontWeight: 620 }}>{inc.suggestedAction}</Typography>
                  <Typography variant="body2" color="text.secondary" sx={{ mt: 0.4 }}>{inc.approval}</Typography>
                </Box>
                <Tag tone={inc.status === 'OPEN' ? 'warn' : 'accent'}>{inc.status === 'OPEN' ? 'HUMAN DECISION PENDING' : 'DECIDED'}</Tag>
              </Box>
            </Panel>
          </Box>
        </Grid>
      </Grid>
    </Box>
  );
}
